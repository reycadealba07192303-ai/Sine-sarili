import { test } from "node:test";
import assert from "node:assert/strict";
import express from "express";
import mongoose from "mongoose";
import { playbackRouter, boundedResponse } from "../src/routes/playback.js";
import { buildDrmConfig, licenseUpstream } from "../src/services/drm.js";
import { ViewerAccount } from "../src/models/viewer-account.js";
import { Subscription } from "../src/models/subscription.js";
import { Film } from "../src/models/film.js";
import { setViewerSessionCookie } from "../src/auth.js";

test("DRM gateway checks entitlement, expiry, asset selection and binary proxying", async t => {
  process.env.MONGODB_URI = "mongodb://test.invalid/test";
  process.env.SESSION_SECRET = "test-secret-longer-than-thirty-two-characters";
  process.env.WEB_ORIGIN = "https://cinema.example";
  process.env.DRM_ENABLED = "false";
  t.mock.method(mongoose, "connect", async () => mongoose);
  const viewer = { _id: "507f1f77bcf86cd799439011", subscriptionStatus: "active" };
  t.mock.method(ViewerAccount, "findOne", () => ({ select: () => ({ lean: async () => viewer }) }));
  let expired = false;
  t.mock.method(Subscription, "exists", async (query: any) => {
    assert.equal(query.viewerId, viewer._id);
    assert.ok(query.expiresAt.$gt instanceof Date);
    return expired ? null : { _id: "sub" };
  });
  const asset = { videoUrl: "https://cdn.example/film.mpd", drmHlsUrl: "https://cdn.example/master.m3u8", drmAssetId: "asset-one", videoProvider: "drm" };
  let series = false;
  const episodeId = "507f1f77bcf86cd799439012";
  t.mock.method(Film, "findOne", (query: any) => {
    assert.equal(query.status, "published");
    return { lean: async () => ({ ...asset, slug: "test-film", contentType: series ? "series" : "film", seasons: [{ episodes: [{ ...asset, _id: episodeId }] }] }) };
  });
  let cookie = "";
  setViewerSessionCookie({ setHeader: (_: string, value: string) => { cookie = value.split(";")[0]; } } as any, { id: viewer._id, name: "Viewer" });
  const app = express();
  app.use("/api/playback", playbackRouter);
  const server = app.listen(0, "127.0.0.1");
  await new Promise<void>(resolve => server.once("listening", resolve));
  t.after(() => { server.close(); });
  const port = (server.address() as { port: number }).port;
  const local = `http://127.0.0.1:${port}/api/playback/test-film`;
  const originalFetch = globalThis.fetch;
  let calls = 0;
  t.mock.method(globalThis, "fetch", async (url: any, options: any) => {
    if (String(url).startsWith("http://127.0.0.1:")) return originalFetch(url, options);
    calls++;
    assert.equal(String(url), "https://gateway.example/widevine/asset-one");
    assert.equal(options.headers.Authorization, "Bearer gateway-secret");
    assert.equal(options.headers.Cookie, undefined);
    assert.equal(Buffer.from(options.body).toString(), "challenge");
    assert.equal(options.redirect, "error");
    return new Response(new Uint8Array([1, 2, 3]));
  });
  assert.equal((await fetch(local + "/config")).status, 403);
  assert.equal((await fetch(local + "/config", { headers: { Cookie: cookie } })).status, 503);
  process.env.DRM_ENABLED = "true";
  for (const system of ["WIDEVINE", "PLAYREADY", "FAIRPLAY"]) process.env[`DRM_${system}_LICENSE_URL`] = `https://gateway.example/${system.toLowerCase()}/{assetId}`;
  process.env.DRM_FAIRPLAY_CERTIFICATE_URL = "https://gateway.example/certificate.der";
  process.env.DRM_LICENSE_AUTHORIZATION = "Bearer gateway-secret";
  const configResponse = await fetch(local + "/config", { headers: { Cookie: cookie } });
  assert.equal(configResponse.status, 200);
  assert.equal(configResponse.headers.get("cache-control"), "private, no-store");
  const config = await configResponse.json() as any;
  assert.equal(Object.keys(config.data.servers).length, 3);
  assert.ok(!JSON.stringify(config).includes("gateway-secret"));
  assert.ok(!JSON.stringify(config).includes("gateway.example"));
  expired = true;
  assert.equal((await fetch(local + "/license/widevine", { method: "POST", headers: { Cookie: cookie }, body: "challenge" })).status, 403);
  assert.equal(calls, 0);
  expired = false;
  assert.equal((await fetch(local + "/config", { headers: { Cookie: cookie, Origin: "https://untrusted.example" } })).status, 403);
  series = true;
  assert.equal((await fetch(local + "/config", { headers: { Cookie: cookie } })).status, 404);
  assert.equal((await fetch(local + "/config?episode=507f1f77bcf86cd799439099", { headers: { Cookie: cookie } })).status, 404);
  const episode = await fetch(local + "/config?episode=" + episodeId, { headers: { Cookie: cookie } });
  assert.equal(episode.status, 200);
  series = false;
  const license = await fetch(local + "/license/widevine", { method: "POST", headers: { Cookie: cookie, "Content-Type": "application/octet-stream" }, body: "challenge" });
  assert.equal(license.status, 200);
  assert.deepEqual([...new Uint8Array(await license.arrayBuffer())], [1, 2, 3]);
  assert.equal(calls, 1);
  assert.equal((await fetch(local + "/license/clearkey", { method: "POST", headers: { Cookie: cookie }, body: "challenge" })).status, 400);
  assert.equal((await fetch(local + "/license/widevine", { method: "POST", headers: { Cookie: cookie }, body: "x".repeat(262145) })).status, 413);
  assert.equal(licenseUpstream("widevine", "a/b"), "https://gateway.example/widevine/a%2Fb");
  assert.equal(buildDrmConfig("film", "", { ...asset, videoUrl: "http://cdn.example/clear.mp4" }), null);
  await assert.rejects(boundedResponse(new Response(new Uint8Array(1024 * 1024 + 1))), /Oversized/);
});
